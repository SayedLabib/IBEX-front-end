export function getProductBySlug(slug: string) {
  return products.find((p) => p.slug === slug);
}

export function getFeaturedProducts(limit = 8) {
  return products.filter((p) => p.isFeatured).slice(0, limit);
}

export function getNewArrivals(limit = 5) {
  return products.filter((p) => p.isNew).slice(0, limit);
}

export function getBestSellers(limit = 5) {
  return products.filter((p) => p.isBestSeller).slice(0, limit);
}

export function getOnSale() {
  return products.filter((p) => p.comparePrice && p.comparePrice > p.price);
}

export function getRelatedProducts(product: Product, limit = 5) {
  return products.filter((p) => p.categoryId === product.categoryId && p.id !== product.id).slice(0, limit);
}
